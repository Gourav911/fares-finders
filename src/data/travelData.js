export function formatPrice(amountInUSD, currencyObj = currencies[0]) {
  const curr = currencyObj || currencies[0];
  const converted = Math.round(amountInUSD * curr.rate);
  if (curr.code === 'JPY') {
    return `${curr.symbol}${converted.toLocaleString()}`;
  }
  return `${curr.symbol}${converted}`;
}

